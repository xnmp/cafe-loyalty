import { toBase64Url } from '../../src/domain/bytes';
import { bytesEqual } from '../../src/domain/bytes';
import type { CafeConfig } from '../../src/domain/config';
import { DEMO_KEY_ID, DEMO_PUBLIC_KEY, demoStaffCode } from '../../src/domain/provisioning';

export function nextKeyId(config: CafeConfig): number {
  const id = Math.max(0, ...config.keys.map((key) => key.id)) + 1;
  if (id > 255) throw new RangeError('No key ids remain (maximum is 255)');
  return id;
}

export function addPublicKey(config: CafeConfig, id: number, publicKey: Uint8Array): CafeConfig {
  if (!Number.isInteger(id) || id <= DEMO_KEY_ID || id > 255) throw new RangeError('Key id must be 1–255 (0 is the demo code\'s)');
  if (config.keys.some((key) => key.id === id)) throw new Error(`Key ${id} already exists`);
  if (publicKey.length !== 32) throw new RangeError('Public key must be 32 bytes');
  if (bytesEqual(publicKey, DEMO_PUBLIC_KEY)) throw new Error("That's the public demo key; trusting it would let anyone issue stamps");
  return { ...config, keys: [...config.keys, { id, publicKey: toBase64Url(publicKey) }] };
}

export function removeKey(config: CafeConfig, id: number): CafeConfig {
  if (!config.keys.some((key) => key.id === id)) throw new Error(`Key ${id} does not exist`);
  if (config.keys.length === 1) throw new Error('Cannot retire the last key');
  return { ...config, keys: config.keys.filter((key) => key.id !== id) };
}

export const escapeHtml = (text: string): string => text.replace(/[&<>"']/g, (char) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
})[char]!);

export interface ProvisioningPage {
  readonly cafeName: string;
  readonly cafeId: string;
  readonly keyId: number;
  readonly staffCode: string;
  /** Trusted SVG generated by qrcode, intentionally rendered as markup. */
  readonly qrSvg: string;
  readonly generatedAt: string;
}

export function renderProvisioningPage(page: ProvisioningPage): string {
  const { cafeName, cafeId, keyId, staffCode, generatedAt } = page;
  // Only the demo code itself is ever called safe to share.
  const demo = staffCode === demoStaffCode(cafeId);
  const heading = demo ? 'Counter mode demo' : 'Counter device setup';
  const notice = demo
    ? "DEMO CODE — safe to share. A counter set up with it works as usual, but customers' cards reject its stamps and it can't give free drinks. It's for app review and staff practice."
    : 'PRIVATE KEY — Anyone with this code can issue stamps. Keep it private. Store it like a key.';
  return `<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(cafeName)} — ${heading}</title>
<style>
  * { box-sizing: border-box; }
  body { max-width: 760px; margin: 32px auto; padding: 0 24px; font: 16px/1.5 system-ui, sans-serif; color: #111; background: #fff; }
  h1 { line-height: 1.2; } .warning { border: 3px solid #111; padding: 16px; font-weight: bold; }
  .qr { margin: 24px auto; width: 6cm; height: 6cm; } .qr svg { display: block; width: 100%; height: 100%; }
  .code { padding: 16px; border: 1px solid #555; font: 14px/1.6 monospace; overflow-wrap: anywhere; white-space: pre-wrap; }
  li { margin-bottom: 6px; } @page { margin: 1.5cm; } @media print { body { margin: 0; max-width: none; padding: 0; } .qr, .code, .warning { break-inside: avoid; } }
</style></head>
<body><h1>${escapeHtml(cafeName)}</h1><h2>${heading}</h2>
<p>Café: ${escapeHtml(cafeId)} · Key id: ${escapeHtml(String(keyId))}${demo ? ' (demo)' : ''}<br>Generated: ${escapeHtml(generatedAt)}</p>
<p class="warning">${escapeHtml(notice)}</p>
<div class="qr">${page.qrSvg}</div>
<ol><li>Install the app on the counter phone.</li><li>Open About: the ⓘ button at the top of the card screen.</li><li>Press and hold the version number at the bottom for 2 seconds.</li><li>Tap “Scan staff code” and scan this code, or tap “Paste code instead” and paste the code below.</li><li>Choose a 4-digit staff PIN.</li></ol>
<p>Staff code for manual entry:</p><pre class="code">${escapeHtml(staffCode)}</pre>
</body></html>\n`;
}
